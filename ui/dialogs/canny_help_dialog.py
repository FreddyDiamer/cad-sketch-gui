"""Справочный диалог по параметрам выделения контуров.

Открывается из карточки шага 4 «Контуры» и подробно описывает каждый
из четырёх параметров обработки изображения: оба порога алгоритма
Канни, размер ядра гауссова сглаживания и допуск аппроксимации
Дугласа–Пёкера. Содержит рекомендации по типичным значениям и
типовые проблемы с подсказками, как их исправить.
"""
from __future__ import annotations

from PyQt6.QtCore import Qt
from PyQt6.QtWidgets import (
    QDialog,
    QDialogButtonBox,
    QTextBrowser,
    QVBoxLayout,
)


# HTML-содержимое справки. Вынесено в константу, чтобы при необходимости
# легко править текст, не трогая логику диалога.
_HELP_HTML = """
<h2 style="margin-top:0">Параметры выделения контуров</h2>

<p>Подсистема использует алгоритм <b>Canny</b> — двухступенчатую пороговую
фильтрацию градиентов яркости — с последующей аппроксимацией контуров
методом <b>Дугласа–Пёкера</b>. Ниже описаны все четыре параметра обработки,
доступные на шаге «Контуры», и рекомендации по их настройке.</p>

<hr>

<h3>1. Нижний порог Canny (диапазон 0–255)</h3>
<p>Минимальное значение градиента яркости, при котором пиксель
рассматривается как кандидат в границу. Пиксели с градиентом ниже
этого значения отбрасываются как шум.</p>
<ul>
  <li><b>Слишком низкий</b> — много ложных контуров, появляются «лишние» линии
    на однородных областях.</li>
  <li><b>Слишком высокий</b> — теряются слабые границы (нечёткие края, малоконтрастные участки).</li>
</ul>
<p><b>Рекомендуемый диапазон:</b> 30–80. <b>Значение по умолчанию:</b> 50.</p>

<h3>2. Верхний порог Canny (диапазон 0–255)</h3>
<p>Минимальное значение градиента, при котором пиксель гарантированно
включается в контур. Между нижним и верхним порогом пиксели сохраняются
только если связаны цепочкой с пикселями выше верхнего порога
(«гистерезис»).</p>
<ul>
  <li><b>Правило:</b> верхний порог должен быть в <b>2–3 раза больше нижнего</b>.</li>
  <li><b>Слишком низкий</b> — много шума на местах контрастных переходов.</li>
  <li><b>Слишком высокий</b> — пропускаются менее контрастные границы детали.</li>
</ul>
<p><b>Рекомендуемый диапазон:</b> 100–200. <b>Значение по умолчанию:</b> 150.</p>

<h3>3. Размытие — размер ядра Гаусса (нечётное число 3–15)</h3>
<p>Гауссово сглаживание применяется к изображению <b>до</b> Canny.
Задача — подавить высокочастотный шум, чтобы алгоритм не принимал
случайные перепады яркости за границу.</p>
<ul>
  <li><b>Маленькое ядро (3–5)</b> — мелкие детали сохраняются, но шум тоже.</li>
  <li><b>Большое ядро (7–15)</b> — шум подавлен, но размываются мелкие детали
    (тонкие линии, угловые точки).</li>
</ul>
<p><b>Рекомендуемое значение:</b> 5 для большинства фотографий деталей при
ровном освещении. Увеличивать до 7–9 при наличии явного шума или текстуры
(например, обработанная поверхность, ткань, бумажная основа).</p>

<h3>4. Сглаживание — допуск аппроксимации Дугласа–Пёкера (пиксели)</h3>
<p>Максимальное отклонение упрощённой ломаной от исходного контура.
Чем больше допуск, тем меньше точек в результирующем эскизе.</p>
<ul>
  <li><b>Малое (0.5–1.5)</b> — контур точно повторяет границу детали, много
    точек. Подходит для деталей со сложной криволинейной формой.</li>
  <li><b>Большое (3–10)</b> — рёбра спрямляются, контур упрощается. Подходит
    для деталей с прямыми гранями (плоские пластины, прямоугольные пазы).</li>
</ul>
<p><b>Рекомендуемое значение:</b> 2.0 — компромисс между точностью и
количеством точек.</p>

<hr>

<h2>Порядок настройки параметров</h2>

<ol>
  <li>Начните с <b>значений по умолчанию</b>: пороги 50 / 150, ядро 5, сглаживание 2.0.
    Нажмите «Применить» и оцените результат.</li>
  <li>Если контуры <b>прерывистые</b> или часть границы не выделена —
    уменьшите <b>нижний порог</b> (например, до 30).</li>
  <li>Если на однородных областях появляются <b>лишние линии</b> или мелкие
    кляксы — увеличьте <b>размер ядра Гаусса</b> (до 7 или 9) и/или
    повысьте <b>нижний порог</b>.</li>
  <li>Если контур получается <b>«дёрганый»</b>, с большим количеством мелких
    зигзагов — увеличьте <b>сглаживание</b> (до 3–5).</li>
  <li>Если из контура <b>исчезли важные детали</b> (углы, отверстия) —
    наоборот, уменьшите <b>сглаживание</b> (до 1.0–1.5).</li>
</ol>

<p style="color:#8b949e">
Совет: включите флажок «Авто-обновление», чтобы видеть результат
изменений в реальном времени — это сильно ускоряет подбор параметров.
</p>
"""


class CannyHelpDialog(QDialog):
    """Информационный диалог: только текст и кнопка «Закрыть»."""

    def __init__(self, parent=None) -> None:
        super().__init__(parent)
        self.setWindowTitle("Параметры обработки: описание")
        self.setModal(True)
        # Стартовый размер, при котором содержимое читаемо без прокрутки.
        self.resize(640, 560)

        # QTextBrowser поддерживает HTML и сам прокручивает длинный текст.
        # Read-only по умолчанию, ссылки в нашем тексте отсутствуют.
        browser = QTextBrowser()
        browser.setOpenExternalLinks(False)
        browser.setHtml(_HELP_HTML)
        # Базовая типографика: умеренный шрифт, удобные межстрочные интервалы.
        browser.document().setDefaultStyleSheet(
            "body { line-height: 1.55; }"
            "h2 { font-size: 16px; }"
            "h3 { font-size: 14px; margin-top: 14px; }"
            "li { margin-bottom: 4px; }"
            "p  { margin: 6px 0; }"
        )

        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        buttons.rejected.connect(self.reject)
        # У одиночной кнопки Close сигнал — rejected, но привычнее закрывать
        # диалог по клику без статуса «отмена»; маппим оба сигнала на reject.
        buttons.accepted.connect(self.reject)

        layout = QVBoxLayout(self)
        layout.addWidget(browser)
        layout.addWidget(buttons)
        # Включаем стандартное поведение Esc → закрытие.
        self.setWindowFlag(Qt.WindowType.WindowContextHelpButtonHint, False)
